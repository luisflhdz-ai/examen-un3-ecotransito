# TAREA 1: INGESTA, DIAGNÓSTICO Y SUSTITUCIÓN DE CENTINELAS
import pandas as pd
import numpy as np

# 1. Cargar o definir el dataset
data = {
    'ID_Registro': ['REG-001', 'REG-002', 'REG-003', 'REG-004', 'REG-005',
                    'REG-006', 'REG-007', 'REG-008', 'REG-009', 'REG-010', 'REG-010'],
    'Timestamp': ['2026-10-01 08:00:00', '2026-10-01 09:00:00', '2026-10-01 10:00:00',
                  '2026-10-01 11:00:00', '2026-10-01 12:00:00', '2026-10-01 13:00:00',
                  '2026-10-01 14:00:00', '2026-10-01 15:00:00', '2026-10-01 16:00:00',
                  '2026-10-01 17:00:00', '2026-10-01 17:00:00'],
    'Zona_Estacion': ['Centro_Historico', 'centro_historico', 'CENTRO_HISTORICO',
                      'Zona_Oriente', 'Zona_Oriente', 'zona_oriente', 'Zona_Sur',
                      'Zona_Sur', 'Zona_Sur', 'Zona_Sur', 'Zona_Sur'],
    'Concentracion_PM25': [35.4, 42.1, -999.0, 120.5, np.nan, 310.0, 18.2, 20.1, 19.5, 19.5, 19.5],
    'Nivel_NO2': [42.1, 48.5, 51.0, 89.2, 82.0, 195.0, 22.4, -999.0, 25.1, 25.1, 25.1],
    'Indice_Trafico_Vehicular': [85.0, 92.5, 88.0, 98.0, 91.2, 15.0, 45.0, 42.1, np.nan, 41.0, 41.0],
    'Estado_Sensor': ['Normal', 'Normal', 'Alerta', 'Alerta', 'Normal', 'Falla',
                      'Normal', 'Normal', 'Normal', 'Normal', 'Normal']
}

df_raw = pd.DataFrame(data)

# ESCRIBE TU CÓDIGO AQUÍ:
# ------------------------------------------------------------------------------
# a) Diagnóstico inicial de duplicados y centinelas
cols_numericas = ['Concentracion_PM25', 'Nivel_NO2', 'Indice_Trafico_Vehicular']

print("=== DIAGNÓSTICO INICIAL ===")
print(f"Total de filas antes de limpieza: {len(df_raw)}")
print(f"Filas totalmente duplicadas detectadas: {df_raw.duplicated().sum()}\n")

print("Conteo de valores faltantes explícitos (NaN) en columnas numéricas:")
print(df_raw[cols_numericas].isna().sum(), "\n")

print("Conteo de valores centinela (-999.0) en columnas numéricas:")
print((df_raw[cols_numericas] == -999.0).sum(), "\n")

# b) Reemplazar centinela -999.0 por np.nan y eliminar duplicados
df_raw[cols_numericas] = df_raw[cols_numericas].replace(-999.0, np.nan)
df_raw = df_raw.drop_duplicates().reset_index(drop=True)

print("=== DATAFRAME TRAS REEMPLAZAR CENTINELAS Y ELIMINAR DUPLICADOS ===")
print(f"Total de filas después de eliminar duplicados: {len(df_raw)}")
print("Conteo actualizado de NaN por columna numérica:")
print(df_raw[cols_numericas].isna().sum(), "\n")
print(df_raw)

# TAREA 2: PIPELINE DE LIMPIEZA, FEATURE ENGINEERING E IMPUTACIÓN
from sklearn.impute import KNNImputer

df_clean = df_raw.copy()

# ESCRIBE TU CÓDIGO AQUÍ:
# ------------------------------------------------------------------------------
# 1. Homogeneizar 'Zona_Estacion'
df_clean['Zona_Estacion'] = (
    df_clean['Zona_Estacion']
    .str.strip()
    .str.replace(' ', '_')
    .str.title()
)

# 2. Convertir Timestamp a datetime y extraer Hora_Dia
df_clean['Timestamp'] = pd.to_datetime(df_clean['Timestamp'])
df_clean['Hora_Dia'] = df_clean['Timestamp'].dt.hour

# 3. Detección de outliers por IQR en 'Concentracion_PM25' y sustitución por np.nan
Q1 = df_clean['Concentracion_PM25'].quantile(0.25)
Q3 = df_clean['Concentracion_PM25'].quantile(0.75)
IQR = Q3 - Q1
limite_inferior = Q1 - 1.5 * IQR
limite_superior = Q3 + 1.5 * IQR

print(f"Diagnóstico IQR PM2.5 -> Q1: {Q1:.2f}, Q3: {Q3:.2f}, IQR: {IQR:.2f}, Límite Superior: {limite_superior:.2f}")

condicion_outlier = (df_clean['Concentracion_PM25'] < limite_inferior) | (df_clean['Concentracion_PM25'] > limite_superior)
print(f"Outliers detectados en Concentracion_PM25: {condicion_outlier.sum()} (Valor: {df_clean.loc[condicion_outlier, 'Concentracion_PM25'].values})\n")

df_clean.loc[condicion_outlier, 'Concentracion_PM25'] = np.nan

# 4. Imputación avanzada k-NN sobre variables numéricas
cols_imputar = ['Concentracion_PM25', 'Nivel_NO2', 'Indice_Trafico_Vehicular']
imputer = KNNImputer(n_neighbors=2)
df_clean[cols_imputar] = imputer.fit_transform(df_clean[cols_imputar])

print("=== DATAFRAME LIMPIO E IMPUTADO (df_clean) ===")
print(df_clean)
